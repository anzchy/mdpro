/** Derive a complete validated write plan before touching any generated fixture or canonical shard. */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { canonicalJson } from '../../tests/support/corpus/canonical.ts';
import { safeRelativePath } from '../../tests/support/corpus/metadata.ts';
import { isObject } from '../../tests/support/corpus/metadataActions.ts';
import { checkData, loadCorpus } from './core.ts';
import { readTree } from './files.ts';
import { verifyBaseline as gitVerify } from './provenance.ts';
export interface MergeOptions { mergeBaseSha: string; caseIds?: readonly string[]; verifyBaseline?: (sha: string) => void }
export function planMerge(root: string, scratch: string, options: MergeOptions) {
  const data = loadCorpus(root), generated = readTree(scratch), prospective = structuredClone(data);
  const verify = options.verifyBaseline ?? gitVerify;
  if (!/^[a-f0-9]{40}$/i.test(options.mergeBaseSha)) throw new Error('baselineSha merge base must be40hex');
  verify(options.mergeBaseSha);
  const selected = options.caseIds ? [...options.caseIds] : data.records.filter(record => record.status === 'active').map(record => record.caseId);
  if (!selected.length || new Set(selected).size !== selected.length || selected.some(id => !data.records.some(record => record.caseId === id && record.status === 'active'))) throw new Error('invalid selected case results');
  const expectedPaths = selected.map(id => `results/${id}.json`);
  for (const path of Object.keys(generated)) if (!expectedPaths.includes(path)) throw new Error(`${path}: unexpected scratch output`);
  for (const path of expectedPaths) if (!Object.hasOwn(generated, path)) throw new Error(`${path}: missing scratch result`);
  const authored = new Set<string>();
  for (const record of data.records) {
    if (record.caseKind === 'guard-only') authored.add(record.recipe.path);
    else { authored.add(record.input); if (record.desired) authored.add(record.desired); }
  }
  const writes = new Map<string, string>(), changed: string[] = [];
  const claimed = new Set<string>();
  const output = (path: string, bytes: string) => {
    if (!safeRelativePath(path) || authored.has(path) || claimed.has(path)) throw new Error(`${path}: forbidden or overlapping generated target`);
    claimed.add(path); prospective.files[path] = bytes;
    if (data.files[path] !== bytes) writes.set(path, bytes);
  };
  for (const id of selected) {
    const record = data.records.find(record => record.caseId === id)!;
    const next = prospective.records.find(record => record.caseId === id)!;
    let payload: unknown;
    try { payload = JSON.parse(generated[`results/${id}.json`].toString('utf8')); } catch { throw new Error(`${id}: invalid scratch JSON result`); }
    if (!isObject(payload) || Object.keys(payload).sort().join(',') !== 'actual,caseId,record,report' || payload.caseId !== id ||
        !isObject(payload.record) || !isObject(payload.actual) || !isObject(payload.report)) throw new Error(`${id}: invalid scratch output result`);
    const actual = payload.actual;
    let same: boolean;
    if (record.caseKind === 'guard-only') {
      if (Object.keys(actual).join(',') !== 'observation') throw new Error(`${id}: invalid guard output`);
      same = canonicalJson(actual.observation) === canonicalJson(record.expected.observation);
      if (next.caseKind !== 'guard-only') throw new Error(`${id}: case kind drift`);
      next.expected.observation = actual.observation as typeof next.expected.observation;
    } else {
      if (typeof actual.serialized !== 'string' || actual.untouched !== data.files[record.input] ||
          Object.keys(actual).some(key => !['serialized', 'untouched', 'observation'].includes(key))) throw new Error(`${id}: invalid serialized/untouched output`);
      if (!!record.expected.observation !== Object.hasOwn(actual, 'observation')) throw new Error(`${id}: observation output does not match declared path`);
      same = actual.serialized === data.files[record.expected.serialized] && (!record.expected.observation || canonicalJson(actual.observation) === data.files[record.expected.observation]);
      output(record.expected.serialized, actual.serialized);
      if (record.expected.observation) output(record.expected.observation, canonicalJson(actual.observation));
    }
    if (canonicalJson(payload.record) !== canonicalJson(record)) {
      // A repeated merge may only consume its own stale provenance after all generated bytes already match.
      const snapshot = structuredClone(payload.record);
      snapshot.baselineSha = record.baselineSha;
      if (record.caseKind === 'guard-only' && isObject(snapshot.expected)) snapshot.expected.observation = record.expected.observation;
      if (!same || record.baselineSha !== options.mergeBaseSha || canonicalJson(snapshot) !== canonicalJson(record)) throw new Error(`${id}: scratch record snapshot drift`);
      verify(String(payload.record.baselineSha));
    }
    if (!same) { next.baselineSha = options.mergeBaseSha; changed.push(id); }
  }
  // structuredClone preserves shared references between records and their original shards.
  const errors = checkData(prospective, { verifyBaseline: verify });
  if (errors.length) throw new Error(errors.join('\n'));
  for (const [path, records] of Object.entries(prospective.shards)) {
    const bytes = canonicalJson(records);
    if (bytes !== canonicalJson(data.shards[path])) writes.set(path, bytes);
  }
  return { data: prospective, writes, changed: changed.sort() };
}
export function mergeScratch(root: string, scratch: string, options: MergeOptions): string[] {
  const plan = planMerge(root, scratch, options);
  for (const [path, bytes] of plan.writes) { const target = join(plan.data.root, path); mkdirSync(dirname(target), { recursive: true }); writeFileSync(target, bytes); }
  return plan.changed;
}
