/**
 * WI-7 (ADR-0047): the version group of the build manifest —
 * `cargoLockVersions` (crates from `Cargo.lock`), `readNodeModuleVersion`
 * (JS packages from `node_modules/<pkg>/package.json`) and `collectVersions`
 * (the 10-key aggregate).
 * Matrix: `.claude/tdd-guardian/tests-20261002-155158.md`, unit WI-7, T01..T09;
 * plan decisions O8 and O14: every requested name is a key, each value is a
 * de-duplicated array sorted by numeric semver precedence, absent gives `[]`.
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";
import {
  VersionsError,
  cargoLockVersions,
  collectVersions,
  readNodeModuleVersion,
  // @ts-expect-error -- plain ESM script, no .d.ts by design
} from "../scripts/control/versions.mjs";

type VersionMap = Record<string, string[]>;

const CRATES = [
  "tauri",
  "tauri-build",
  "wry",
  "tao",
  "tauri-plugin-opener",
  "tauri-plugin-single-instance",
  "tauri-plugin-updater",
  "tauri-plugin-process",
];
const JS = ["@tauri-apps/api", "@tauri-apps/cli"];
const ALL_TEN = [...CRATES, ...JS];

const REGISTRY = 'source = "registry+https://github.com/rust-lang/crates.io-index"';
const HEADER = [
  "# This file is automatically @generated by Cargo.",
  "# It is not intended for manual editing.",
  "version = 4",
  "",
].join("\n");

/** One `[[package]]` block in Cargo's lock-file layout. */
function pkg(name: string, version: string, extra: string[] = [REGISTRY]): string {
  return ["[[package]]", `name = "${name}"`, `version = "${version}"`, ...extra, ""].join("\n");
}
const lock = (...blocks: string[]): string => HEADER + "\n" + blocks.join("\n");

const T01_BLOCKS = {
  tauri: pkg("tauri", "2.12.1", [REGISTRY, "dependencies = [", ' "tao",', ' "wry",', "]"]),
  "tauri-build": pkg("tauri-build", "2.5.0"),
  wry: pkg("wry", "0.53.5"),
  tao: pkg("tao", "0.34.5"),
  "tauri-plugin-opener": pkg("tauri-plugin-opener", "2.5.3"),
  "tauri-plugin-single-instance": pkg("tauri-plugin-single-instance", "2.3.7"),
  "tauri-plugin-updater": pkg("tauri-plugin-updater", "2.9.0"),
  "tauri-plugin-process": pkg("tauri-plugin-process", "2.3.1"),
};
const UNRELATED = [pkg("serde", "1.0.228"), pkg("adler2", "2.0.1"), pkg("tauri-app", "0.6.0", [])];
const T01_LOCK = lock(UNRELATED[0], ...Object.values(T01_BLOCKS), UNRELATED[1], UNRELATED[2]);

const T01_EXPECTED: VersionMap = {
  tauri: ["2.12.1"],
  "tauri-build": ["2.5.0"],
  wry: ["0.53.5"],
  tao: ["0.34.5"],
  "tauri-plugin-opener": ["2.5.3"],
  "tauri-plugin-single-instance": ["2.3.7"],
  "tauri-plugin-updater": ["2.9.0"],
  "tauri-plugin-process": ["2.3.1"],
};

// ---------------------------------------------------------------------------
// Real tmpdir I/O
// ---------------------------------------------------------------------------
const made: string[] = [];
function tmp(): string {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), "mdpro-versions-"));
  made.push(d);
  return d;
}
afterEach(() => {
  for (const d of made.splice(0)) fs.rmSync(d, { recursive: true, force: true });
});
function put(root: string, rel: string, content: string): void {
  const p = path.join(root, ...rel.split("/"));
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, content);
}

describe("cargoLockVersions (WI-7)", () => {
  it("WI-7/T01 fixture lock gives an exact map for the 8 crates", () => {
    const r: VersionMap = cargoLockVersions(T01_LOCK, CRATES);
    expect(r).toEqual(T01_EXPECTED);
    expect(Object.keys(r).sort()).toEqual([...CRATES].sort());
  });

  it("WI-7/T02 two versions of one crate are both listed, numerically sorted; pre-releases sort first", () => {
    const twoTao = lock(T01_BLOCKS.tauri, pkg("tao", "0.34.0"), pkg("tao", "0.9.1"));
    expect(cargoLockVersions(twoTao, ["tao"]).tao).toEqual(["0.9.1", "0.34.0"]);

    const wryPre = lock(pkg("wry", "2.0.0"), pkg("wry", "2.0.0-rc.1"), pkg("wry", "2.0.0-beta.2"));
    expect(cargoLockVersions(wryPre, ["wry"]).wry).toEqual(["2.0.0-beta.2", "2.0.0-rc.1", "2.0.0"]);
  });

  it("WI-7/T03 an absent crate is [], never omitted", () => {
    const { "tauri-plugin-process": _dropped, ...rest } = T01_BLOCKS;
    const r: VersionMap = cargoLockVersions(lock(...Object.values(rest)), CRATES);
    expect(r["tauri-plugin-process"]).toEqual([]);
    expect(Object.keys(r).length).toBe(8);
    expect(r.tauri).toEqual(["2.12.1"]);

    const empty: VersionMap = cargoLockVersions("", CRATES);
    expect(Object.keys(empty).sort()).toEqual([...CRATES].sort());
    for (const name of CRATES) expect(empty[name], name).toEqual([]);
  });

  it("WI-7/T04 no prefix bleed and no dependency-list bleed", () => {
    const text = lock(
      pkg("tauri-build", "2.5.0"),
      pkg("tauri-plugin-opener-extra", "9.9.9"),
      pkg("foo", "1.2.3", [REGISTRY, 'dependencies = ["tauri 1.0.0", "tao 0.1.0"]']),
      pkg("bar", "4.5.6", [REGISTRY, "dependencies = [", ' "tauri-plugin-opener 2.0.0",', ' "wry",', "]"]),
    );
    const r: VersionMap = cargoLockVersions(text, CRATES);
    expect(r.tauri).toEqual([]);
    expect(r["tauri-plugin-opener"]).toEqual([]);
    expect(r.tao).toEqual([]);
    expect(r.wry).toEqual([]);
    expect(r["tauri-build"]).toEqual(["2.5.0"]);
  });

  it("WI-7/T05 only the requested names come back", () => {
    const r: VersionMap = cargoLockVersions(T01_LOCK, ["tao"]);
    expect(r).toEqual({ tao: ["0.34.5"] });
    expect(Object.keys(r)).toHaveLength(1);
  });

  it("WI-7/T09 a duplicated version is listed once", () => {
    const text = lock(
      pkg("tao", "0.34.0"),
      pkg("tao", "0.34.0", ['source = "git+https://github.com/tauri-apps/tao#abc123"']),
      pkg("tao", "0.9.1"),
    );
    const r: VersionMap = cargoLockVersions(text, ["tao"]);
    expect(r.tao).toEqual(["0.9.1", "0.34.0"]);
    expect(r.tao).toHaveLength(2);
  });
});

describe("readNodeModuleVersion (WI-7)", () => {
  it("WI-7/T06 reads node_modules/<pkg>/package.json: present, missing, bad JSON, non-string version", () => {
    const root = tmp();
    put(root, "node_modules/@tauri-apps/cli/package.json", '{"name":"@tauri-apps/cli","version":"2.12.1"}');
    put(root, "node_modules/bad-json/package.json", '{"version": "1.0.0",');
    put(root, "node_modules/bad-version/package.json", '{"version": 3}');

    expect(readNodeModuleVersion(root, "@tauri-apps/cli")).toEqual(["2.12.1"]);
    expect(readNodeModuleVersion(root, "@tauri-apps/api")).toEqual([]);
    expect(() => readNodeModuleVersion(root, "bad-json")).toThrow(/bad-json/);
    expect(() => readNodeModuleVersion(root, "bad-version")).toThrow(/bad-version/);
  });
});

describe("collectVersions (WI-7)", () => {
  it("WI-7/T07 aggregator: 10 keys, missing values are []", () => {
    const root = tmp();
    put(root, "src-tauri/Cargo.lock", lock(pkg("tauri", "2.9.5")));
    put(root, "node_modules/@tauri-apps/api/package.json", '{"name":"@tauri-apps/api","version":"2.9.1"}');

    const r: VersionMap = collectVersions(root);
    expect(Object.keys(r).sort()).toEqual([...ALL_TEN].sort());
    expect(r.tao).toEqual([]);
    expect(r["@tauri-apps/cli"]).toEqual([]);
    expect(r.tauri).toEqual(["2.9.5"]);
    expect(r["@tauri-apps/api"]).toEqual(["2.9.1"]);
    for (const name of ALL_TEN) expect(Array.isArray(r[name]), name).toBe(true);
  });

  it("WI-7/T08 live repo smoke test: 10 keys, tauri and @tauri-apps/api present (no pinned numbers)", () => {
    const repoRoot = fileURLToPath(new URL("..", import.meta.url));
    const r: VersionMap = collectVersions(repoRoot);
    const SEMVER_PREFIX = /^\d+\.\d+\.\d+/;

    expect(Object.keys(r).sort()).toEqual([...ALL_TEN].sort());
    for (const name of ALL_TEN) expect(Array.isArray(r[name]), name).toBe(true);
    expect(r.tauri.length).toBeGreaterThanOrEqual(1);
    for (const v of r.tauri) expect(v).toMatch(SEMVER_PREFIX);
    expect(r["@tauri-apps/api"]).toHaveLength(1);
    expect(r["@tauri-apps/api"][0]).toMatch(SEMVER_PREFIX);
  });
});

// WI-21 pins (matrix `tests-20261002-201520.md`; T10 lives in control-build-versions-order.test.ts).
describe("WI-21 version-source guards (WI-7)", () => {
  it("WI-7/T11 a missing src-tauri/Cargo.lock throws VersionsError naming the file", () => {
    const root = tmp();
    expect(fs.existsSync(path.join(root, "src-tauri"))).toBe(false);
    expect(() => collectVersions(root)).toThrow(VersionsError);
    expect(() => collectVersions(root)).toThrow("collectVersions: cannot read src-tauri/Cargo.lock: ");
  });

  it("WI-7/T12 an empty version string throws VersionsError naming the package; a real one reads", () => {
    const root = tmp();
    put(root, "node_modules/@tauri-apps/cli/package.json", '{"name":"@tauri-apps/cli","version":""}');
    expect(() => readNodeModuleVersion(root, "@tauri-apps/cli")).toThrow(VersionsError);
    expect(() => readNodeModuleVersion(root, "@tauri-apps/cli")).toThrow(
      'readNodeModuleVersion: package.json of @tauri-apps/cli has no string "version"',
    );

    const ok = tmp();
    put(ok, "node_modules/@tauri-apps/cli/package.json", '{"name":"@tauri-apps/cli","version":"2.0.0"}');
    expect(readNodeModuleVersion(ok, "@tauri-apps/cli")).toEqual(["2.0.0"]);
  });
});
