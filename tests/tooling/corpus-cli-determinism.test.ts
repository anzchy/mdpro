// @vitest-environment node
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, readdirSync, symlinkSync, existsSync } from 'node:fs';
import { rm } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { afterEach, expect, it } from 'vitest';
import { spawnBudget } from '../support/spawnBudget.ts';
import { canonicalJson } from '../support/corpus/canonical.ts';
import type { MountingRecord } from '../support/corpus/types.ts';
import { writeScratchResult } from '../../scripts/corpus/scratch.ts';
import { generateCorpus } from '../../scripts/corpus/generation.ts';
import { determinismCorpus } from '../../scripts/corpus/determinism.ts';
const roots: string[] = [];
afterEach(async () => { const paths = roots.splice(0); await Promise.all(paths.map(path => rm(path, { force: true, recursive: true }))); });
function temp() { const root = mkdtempSync(join(tmpdir(), 'corpus-determinism-')); roots.push(root); return root; }
function fixture() {
  const root = temp(), record: MountingRecord = { caseId: 'a-test', category: 'a', status: 'active', actionGroup: 'no-edit', fidelityTag: 'known-limitation',
    baselineSha: 'a'.repeat(40), input: 'no-edit/a/input.md', desired: 'no-edit/a/desired.md', expected: { serialized: 'no-edit/a/expected.md' },
    action: [], normalizations: [], platform: 'any', reason: 'Known loss.', limitRef: 'D197', rationale: 'Authored input.',
    guardedPaths: [{ path: 'src/empty.ts', receipt: 'MIG001-a-empty' }], consumers: [], negative: { kind: 'matchDesiredOnBaseline' } };
  mkdirSync(join(root, 'no-edit/a'), { recursive: true });
  for (const [path, text] of [[record.input, 'A\n'], [record.expected.serialized, 'OLD\n'], [record.desired!, 'DESIRED\n'], ['a.json', canonicalJson([record])]]) writeFileSync(join(root, path), text);
  return { root, record };
}
function inventory(root: string) { return Object.fromEntries(readdirSync(root, { recursive: true, withFileTypes: true }).filter(entry => entry.isFile()).map(entry => {
  const path = join(entry.parentPath, entry.name); return [path.slice(root.length + 1), readFileSync(path).toString('hex')];
})); }
const provenance = { verifyBaseline: (_sha: string) => {}, mergeBase: () => 'b'.repeat(40) };
it('generates twice into independent scratch directories and compares them without merging fixtures', async () => {
  const { root, record } = fixture(), before = inventory(root), scratches: string[] = [];
  await determinismCorpus({ root, env: {} }, { ...provenance, runRunners: async request => {
    scratches.push(request.scratch); roots.push(request.scratch);
    writeScratchResult(request.scratch, record, { caseId: record.caseId, caseKind: 'mounting', actual: { untouched: 'A\n', serialized: 'NEW\n' }, report: {} });
  } });
  expect(scratches).toHaveLength(2); expect(scratches[0]).not.toBe(scratches[1]); expect(inventory(root)).toEqual(before);
}, spawnBudget(8));
it('reports independent generated byte drift while leaving original fixtures unchanged', async () => {
  const { root, record } = fixture(), before = inventory(root); let count = 0;
  await expect(determinismCorpus({ root, env: {} }, { ...provenance, runRunners: async request => {
    roots.push(request.scratch); writeScratchResult(request.scratch, record, { caseId: record.caseId, caseKind: 'mounting', actual: { untouched: 'A\n', serialized: count++ ? 'DIFFERENT\n' : 'NEW\n' }, report: {} });
  } })).rejects.toThrow(/a-test.json.*differ/);
  expect(inventory(root)).toEqual(before);
}, spawnBudget(7));
it('rejects an ancestor-symlink scratch alias into fixtures before mkdir or child execution', async () => {
  const { root } = fixture(), alias = temp(), before = inventory(root); symlinkSync(root, join(alias, 'alias'));
  const scratch = join(alias, 'alias', 'generated'); let called = false;
  await expect(generateCorpus({ root, scratch, env: {} }, { ...provenance, runRunners: async () => { called = true; } })).rejects.toThrow(/symlink|outside fixture/);
  expect(called).toBe(false); expect(existsSync(join(root, 'generated'))).toBe(false); expect(inventory(root)).toEqual(before);
}, spawnBudget(3));
it('rejects a dot-dot-prefixed scratch directory that is still inside the fixture root', async () => {
  const { root } = fixture(); let called = false;
  await expect(generateCorpus({ root, scratch: join(root, '..escape'), env: {} }, { ...provenance, runRunners: async () => { called = true; } })).rejects.toThrow(/outside fixture/);
  expect(called).toBe(false); expect(existsSync(join(root, '..escape'))).toBe(false);
}, spawnBudget(2));
